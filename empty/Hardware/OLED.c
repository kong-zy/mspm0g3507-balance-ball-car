static void OLED_Delay(void)
{
    volatile uint32_t i;

    /*
     * 软件 IIC 边沿延时。主频 80MHz 时，这个延时让总线速度低于 SSD1306
     * 的快速模式上限，也能更好适应较长杜邦线。
     */
    for (i = 0; i < 80U; i++) {
        __NOP();
    }
}

static void OLED_SCL_High(void)
{
    DL_GPIO_setPins(OLED_PORT, OLED_SCL_PIN);
}

static void OLED_SCL_Low(void)
{
    DL_GPIO_clearPins(OLED_PORT, OLED_SCL_PIN);
}

static void OLED_SDA_High(void)
{
    DL_GPIO_setPins(OLED_PORT, OLED_SDA_PIN);
}

static void OLED_SDA_Low(void)
{
    DL_GPIO_clearPins(OLED_PORT, OLED_SDA_PIN);
}

static void OLED_I2C_Start(void)
{
    OLED_SDA_High();
    OLED_SCL_High();
    OLED_Delay();
    OLED_SDA_Low();
    OLED_Delay();
    OLED_SCL_Low();
}

static void OLED_I2C_Stop(void)
{
    OLED_SCL_Low();
    OLED_SDA_Low();
    OLED_Delay();
    OLED_SCL_High();
    OLED_Delay();
    OLED_SDA_High();
}

static void OLED_I2C_WriteByte(uint8_t data)
{
    uint8_t i;

    for (i = 0U; i < 8U; i++) {
        if ((data & 0x80U) != 0U) {
            OLED_SDA_High();
        } else {
            OLED_SDA_Low();
        }

        OLED_Delay();
        OLED_SCL_High();
        OLED_Delay();
        OLED_SCL_Low();
        data <<= 1;
    }

    /*
     * 原厂示例是不读取 ACK 的无应答写法。这里保留一个 ACK 时钟，
     * 让 SSD1306 完成应答位后继续发送。
     */
    OLED_SDA_High();
    OLED_Delay();
    OLED_SCL_High();
    OLED_Delay();
    OLED_SCL_Low();
}

static void OLED_Write_Byte(uint8_t control, uint8_t data)
{
    OLED_I2C_Start();
    OLED_I2C_WriteByte((OLED_I2C_ADDR << 1) | 0x00U);
    OLED_I2C_WriteByte(control);
    OLED_I2C_WriteByte(data);
    OLED_I2C_Stop();
}

void OLED_Write_Cmd(uint8_t cmd)
{
    OLED_Write_Byte(OLED_CMD_CONTROL_BYTE, cmd);
}

void OLED_Write_Data(uint8_t data)
{
    OLED_Write_Byte(OLED_DATA_CONTROL_BYTE, data);
}

void OLED_Set_Pos(uint8_t x, uint8_t page)
{
    if (x >= OLED_WIDTH) {
        x = OLED_WIDTH - 1U;
    }
    if (page >= OLED_PAGE_NUM) {
        page = OLED_PAGE_NUM - 1U;
    }

    OLED_Write_Cmd((uint8_t)(0xB0U + page));
    OLED_Write_Cmd((uint8_t)(0x00U | (x & 0x0FU)));
    OLED_Write_Cmd((uint8_t)(0x10U | ((x >> 4U) & 0x0FU)));
}

void OLED_Fill(uint8_t data)
{
    uint8_t page;
    uint8_t x;

    for (page = 0U; page < OLED_PAGE_NUM; page++) {
        OLED_Set_Pos(0U, page);
        for (x = 0U; x < OLED_WIDTH; x++) {
            OLED_Write_Data(data);
        }
    }
}

void OLED_Clear(void)
{
    OLED_Fill(0x00U);
}

void OLED_ShowChar(uint8_t x, uint8_t page, char chr)
{
    uint8_t i;
    uint8_t index;

    if ((x > (OLED_WIDTH - 6U)) || (page >= OLED_PAGE_NUM)) {
        return;
    }

    if ((chr < ' ') || (chr > '~')) {
        chr = '?';
    }

    index = (uint8_t)(chr - ' ');
    OLED_Set_Pos(x, page);
    for (i = 0U; i < 6U; i++) {
        OLED_Write_Data(g_oledFont6x8[index][i]);
    }
}

void OLED_ShowString(uint8_t x, uint8_t page, const char *str)
{
    while ((*str != '\0') && (page < OLED_PAGE_NUM)) {
        if (x > (OLED_WIDTH - 6U)) {
            x = 0U;
            page++;
            if (page >= OLED_PAGE_NUM) {
                break;
            }
        }

        OLED_ShowChar(x, page, *str++);
        x = (uint8_t)(x + 6U);
    }
}

void OLED_ShowUnsignedNum(uint8_t x, uint8_t page, uint32_t num)
{
    char buf[11];
    uint8_t i = 0U;
    uint8_t j;

    if (num == 0U) {
        OLED_ShowChar(x, page, '0');
        return;
    }

    while ((num > 0U) && (i < sizeof(buf))) {
        buf[i++] = (char)('0' + (num % 10U));
        num /= 10U;
    }

    for (j = 0U; j < i; j++) {
        OLED_ShowChar((uint8_t)(x + j * 6U), page, buf[i - 1U - j]);
    }
}

void OLED_ShowSignedNum(uint8_t x, uint8_t page, int32_t num)
{
    if (num < 0) {
        OLED_ShowChar(x, page, '-');
        OLED_ShowUnsignedNum((uint8_t)(x + 6U), page, (uint32_t)(-num));
    } else {
        OLED_ShowUnsignedNum(x, page, (uint32_t)num);
    }
}

void OLED_Init(void)
{
    /*
     * SYSCFG_DL_init() 已经完成 GPIO 模块上电。这里再次配置 PA1/PA0，
     * 让它们作为 OLED 软件 IIC 总线的 GPIO 输出引脚使用。
     */
    DL_GPIO_initDigitalOutputFeatures(OLED_SCL_IOMUX,
        DL_GPIO_INVERSION_DISABLE, DL_GPIO_RESISTOR_PULL_UP,
        DL_GPIO_DRIVE_STRENGTH_LOW, DL_GPIO_HIZ_DISABLE);
    DL_GPIO_initDigitalOutputFeatures(OLED_SDA_IOMUX,
        DL_GPIO_INVERSION_DISABLE, DL_GPIO_RESISTOR_PULL_UP,
        DL_GPIO_DRIVE_STRENGTH_LOW, DL_GPIO_HIZ_DISABLE);

    DL_GPIO_setPins(OLED_PORT, OLED_SCL_PIN | OLED_SDA_PIN);
    DL_GPIO_enableOutput(OLED_PORT, OLED_SCL_PIN | OLED_SDA_PIN);

    delay_ms(100);

    OLED_Write_Cmd(0xAE); /* 关闭显示 */
    OLED_Write_Cmd(0x20); /* 设置显存寻址模式 */
    OLED_Write_Cmd(0x10); /* 页寻址模式 */
    OLED_Write_Cmd(0xB0); /* 设置页起始地址 */
    OLED_Write_Cmd(0xC8); /* 设置 COM 扫描方向 */
    OLED_Write_Cmd(0x00); /* 设置列地址低 4 位 */
    OLED_Write_Cmd(0x10); /* 设置列地址高 4 位 */
    OLED_Write_Cmd(0x40); /* 设置显示起始行 */
    OLED_Write_Cmd(0x81); /* 设置对比度 */
    OLED_Write_Cmd(0xDF);
    OLED_Write_Cmd(0xA1); /* 设置段重映射 */
    OLED_Write_Cmd(0xA6); /* 正常显示，不反色 */
    OLED_Write_Cmd(0xA8); /* 设置复用率 */
    OLED_Write_Cmd(0x3F);
    OLED_Write_Cmd(0xA4); /* 显示内容跟随显存 */
    OLED_Write_Cmd(0xD3); /* 设置显示偏移 */
    OLED_Write_Cmd(0x00);
    OLED_Write_Cmd(0xD5); /* 设置显示时钟 */
    OLED_Write_Cmd(0xF0);
    OLED_Write_Cmd(0xD9); /* 设置预充电周期 */
    OLED_Write_Cmd(0x22);
    OLED_Write_Cmd(0xDA); /* 设置 COM 引脚硬件配置 */
    OLED_Write_Cmd(0x12);
    OLED_Write_Cmd(0xDB); /* 设置 VCOMH 电压 */
    OLED_Write_Cmd(0x20);
    OLED_Write_Cmd(0x8D); /* 使能电荷泵 */
    OLED_Write_Cmd(0x14);
    OLED_Write_Cmd(0xAF); /* 开启显示 */

    OLED_Clear();
}
